function unit(id, title, points, tags) {
  return {
    id,
    title,
    summary: `${title}相关的客观知识点与同步练习范围。`,
    tags,
    points
  };
}

function getUnits(scope) {
  const grade = String((scope && scope.grade) || defaultScope.grade);
  return unitsByGrade[grade] || unitsByGrade[defaultScope.grade];
}

function findUnit(units, unitId) {
  return (units || []).find((unitItem) => unitItem.id === unitId);
}

